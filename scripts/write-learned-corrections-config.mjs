/**
 * Writes learned-corrections-config.js from data/learned-corrections.json
 * so the static Babel app can load committed corrections without a fetch.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const jsonPath = path.join(root, 'data', 'learned-corrections.json');
const outFile = path.join(root, 'learned-corrections-config.js');

let data = { version: 1, updatedAt: null, corrections: [] };
try {
  data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
} catch (e) {
  console.warn('[write-learned-corrections-config] Missing or invalid JSON, writing empty store:', e.message);
}

const contents = `/**
 * AUTO-GENERATED by scripts/write-learned-corrections-config.mjs
 * Source of truth: data/learned-corrections.json (commit this file to share corrections).
 */
window.PLUM_LEARNED_CORRECTIONS = ${JSON.stringify(data, null, 2)};
`;

fs.writeFileSync(outFile, contents, 'utf8');
console.log(
  '[write-learned-corrections-config] Wrote learned-corrections-config.js (',
  (data.corrections || []).length,
  'corrections)'
);
